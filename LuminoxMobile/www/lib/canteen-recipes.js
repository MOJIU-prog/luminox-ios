/* 归一化：把用户写的「西红柿2个」「散装生抽」变成规范名 */
function cleanName(raw) {
  let s = String(raw == null ? '' : raw).trim();
  if (!s) return '';
  /* 去掉括号里的备注、去掉数量、去掉空白 */
  s = s.replace(/[（(][^）)]*[）)]/g, '');
  s = s.replace(/[0-9０-９.]+/g, '');
  s = s.replace(/[（(）)\[\]【】、,，。.;；:：!！?？'"“”‘’/\\|]/g, '');
  s = s.replace(/\s+/g, '');
  return s.trim();
}
function canonIng(raw) {
  const k = cleanName(raw).toLowerCase();
  if (!k) return '';
  if (ING_CANON[k]) return ING_CANON[k];
  /* 包含式匹配：'猪瘦肉片' → '猪肉'；按别名长度从长到短试，避免'肉'抢走'牛肉' */
  const keys = Object.keys(ING_CANON).sort(function (a, b) { return b.length - a.length; });
  for (let i = 0; i < keys.length; i++) {
    if (keys[i].length >= 2 && k.indexOf(keys[i]) >= 0) return ING_CANON[keys[i]];
  }
  return k;
}
function canonSeason(raw) {
  const k = cleanName(raw).toLowerCase();
  if (!k) return '';
  if (SEASON_CANON[k]) return SEASON_CANON[k];
  const keys = Object.keys(SEASON_CANON).sort(function (a, b) { return b.length - a.length; });
  for (let i = 0; i < keys.length; i++) {
    if (keys[i].length >= 2 && k.indexOf(keys[i]) >= 0) return SEASON_CANON[keys[i]];
  }
  return k;
}

